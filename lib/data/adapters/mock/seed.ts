function photo(owner: string, unsplashId: string, alt: string, order: number): ImageRef {
  const meta = UNSPLASH[unsplashId];
  return {
    id: `${owner}-${order}`,
    storagePath: '',
    url: `https://images.unsplash.com/${unsplashId}?auto=format&fit=crop&w=1600&q=80`,
    alt,
    width: meta.width,
    height: meta.height,
    blurDataURL: meta.blurDataURL,
    order,
    credit: 'Unsplash placeholder',
  };
}

function gallery(owner: string, title: string, ids: string[]) {
  return ids.map((id, index) =>
    photo(owner, id, index === 0 ? `Representative image for ${title}` : `Representative interior or exterior image ${index + 1} for ${title}`, index),
  );
}

